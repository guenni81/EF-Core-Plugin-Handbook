/// <summary>The model versions of the migration tests and the generated operation sequences.</summary>
internal static class Versions
{
    public static void V1(ModelBuilder m) => m.Entity<Invoice>();

    public static void ColumnRenamed(ModelBuilder m)
        => m.Entity<Invoice>().Property(i => i.TenantId).HasColumnName("Mandant");

    public static void TableRenamed(ModelBuilder m)
        => m.Entity<Invoice>(b =>
        {
            b.ToTable("Bills");
            b.Property(i => i.TenantId).HasColumnName("Mandant");
        });

    public static void SchemaMoved(ModelBuilder m)
        => m.Entity<Invoice>(b =>
        {
            b.ToTable("Bills", "sales");
            b.Property(i => i.TenantId).HasColumnName("Mandant");
        });

    public static void WithArchive(ModelBuilder m)
    {
        m.Entity<Invoice>();
        m.Entity<ArchivedInvoice>();
    }

    public static void Empty(ModelBuilder m)
    {
    }

    public static IModel DesignModel(Action<ModelBuilder> model)
        => MappingContext.Create(model).GetService<IDesignTimeModel>().Model;

    /// <summary>Operations generated by EF's differ, SQL generated by the plugin's generator.</summary>
    public static IReadOnlyList<MigrationCommand> Commands(
        Action<ModelBuilder>? source, Action<ModelBuilder> target, string? connectionString = null)
        => Commands(source is null ? null : MappingContext.Create(source),
            MappingContext.Create(target, connectionString));

    /// <summary>The same for two configured contexts (different session keys or schemas).</summary>
    public static IReadOnlyList<MigrationCommand> Commands(MappingContext? source, MappingContext target)
        => Commands(source?.GetService<IDesignTimeModel>().Model, target);

    /// <summary>The same with an already finished source model, e.g. from a snapshot.</summary>
    public static IReadOnlyList<MigrationCommand> Commands(IModel? source, MappingContext target)
    {
        using (target)
        {
            var targetModel = target.GetService<IDesignTimeModel>().Model;
            var operations = Operations(source, target);
            return target.GetService<IMigrationsSqlGenerator>().Generate(operations, targetModel);
        }
    }

    public static IReadOnlyList<MigrationOperation> Operations(IModel? source, MappingContext target)
        => target.GetService<IMigrationsModelDiffer>().GetDifferences(
            source?.GetRelationalModel(),
            target.GetService<IDesignTimeModel>().Model.GetRelationalModel());

    public static List<string> Sql(Action<ModelBuilder>? source, Action<ModelBuilder> target)
        => Commands(source, target).Select(c => c.CommandText.Trim()).ToList();
}

/// <summary>Order of the generated SQL, without a database.</summary>
public class SqlServerMigrationOrderTests
{
    private static void AssertWrapped(List<string> sql, string change, string finalTable)
    {
        var drop = sql.FindIndex(s => s.Contains("DROP SECURITY POLICY", StringComparison.Ordinal));
        var changed = sql.FindIndex(s => s.Contains(change, StringComparison.Ordinal));
        var create = sql.FindLastIndex(s => s.StartsWith("CREATE SECURITY POLICY", StringComparison.Ordinal));

        Assert.True(drop >= 0 && drop < changed, "policy must be dropped before the change");
        Assert.True(create > changed, "policy must be restored after the change");
        Assert.Single(sql, s => s.StartsWith("CREATE SECURITY POLICY", StringComparison.Ordinal));
        Assert.Contains($"ON {finalTable}", sql[create], StringComparison.Ordinal);
    }

    [Fact]
    public void Renaming_the_tenant_column_drops_the_policy_first_and_restores_it_on_the_new_column()
    {
        var sql = Versions.Sql(Versions.V1, Versions.ColumnRenamed);

        AssertWrapped(sql, "sp_rename N'[Invoice].[TenantId]'", "[dbo].[Invoice]");
        Assert.Contains("([Mandant])", sql[^1], StringComparison.Ordinal);
    }

    [Fact]
    public void Renaming_the_table_drops_the_policy_first_and_restores_it_on_the_new_table()
        => AssertWrapped(Versions.Sql(Versions.ColumnRenamed, Versions.TableRenamed),
            "sp_rename N'[Invoice]'", "[dbo].[Bills]");

    [Fact]
    public void Moving_the_table_to_another_schema_restores_the_policy_there()
        => AssertWrapped(Versions.Sql(Versions.TableRenamed, Versions.SchemaMoved),
            "ALTER SCHEMA [sales] TRANSFER", "[sales].[Bills]");

    [Fact]
    public void Down_migration_is_wrapped_the_same_way()
    {
        var sql = Versions.Sql(Versions.ColumnRenamed, Versions.V1);

        AssertWrapped(sql, "sp_rename N'[Invoice].[Mandant]'", "[dbo].[Invoice]");
        Assert.Contains("([TenantId])", sql[^1], StringComparison.Ordinal);
    }

    [Fact]
    public void Unrelated_changes_leave_the_policy_alone()
    {
        var sql = Versions.Sql(Versions.V1, m =>
        {
            Versions.V1(m);
            m.Entity<Note>();
        });

        Assert.DoesNotContain(sql, s => s.Contains("SECURITY POLICY", StringComparison.Ordinal)
                                        && !s.Contains("[Invoice]", StringComparison.Ordinal)
                                        && !s.Contains("[Note]", StringComparison.Ordinal));
        Assert.DoesNotContain(sql, s => s.Contains("DROP SECURITY POLICY", StringComparison.Ordinal));
    }

    [Fact]
    public void Same_table_name_in_two_schemas_gets_two_policy_names()
    {
        var sql = Versions.Sql(null, m =>
        {
            m.Entity<Invoice>();
            m.Entity<ArchivedInvoice>().ToTable("Invoice", "archive");
        });

        Assert.Contains(sql, s => s.StartsWith("CREATE SECURITY POLICY [acme].[tenant_dbo_Invoice]",
            StringComparison.Ordinal));
        Assert.Contains(sql, s => s.StartsWith("CREATE SECURITY POLICY [acme].[tenant_archive_Invoice]",
            StringComparison.Ordinal));
    }

    [Fact]
    public void Rename_without_a_target_model_is_rejected_instead_of_losing_the_policy()
    {
        using var context = MappingContext.Create(Versions.V1);

        var ex = Assert.Throws<InvalidOperationException>(() => context
            .GetService<IMigrationsSqlGenerator>()
            .Generate([new RenameColumnOperation { Table = "Invoice", Name = "TenantId", NewName = "Mandant" }]));
        Assert.Contains("no target model", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void Ambiguous_policy_names_are_rejected_while_the_model_is_built()
    {
        using var context = MappingContext.Create(m =>
        {
            m.Entity<Invoice>().ToTable("c", "a_b");
            m.Entity<ArchivedInvoice>().ToTable("b_c", "a");
        });

        var ex = Assert.Throws<InvalidOperationException>(() => context.Model);
        Assert.Contains("tenant_a_b_c", ex.Message, StringComparison.Ordinal);
    }
}

/// <summary>
/// Generated migrations against a real SQL Server: create, rename, move, migrate back and drop,
/// with read and write isolation checked through the app login after every step.
/// </summary>
public class SqlServerMigrationTests : IClassFixture<SqlServerFixture>
{
    private readonly SqlServerFixture _fixture;

    public SqlServerMigrationTests(SqlServerFixture fixture)
    {
        ArgumentNullException.ThrowIfNull(fixture);

        _fixture = fixture;
    }

    /// <summary>Creates an empty database with a user for the app login.</summary>
    internal static Task<(string Owner, string App)> CreateDatabaseAsync(SqlServerFixture fixture)
        => new SqlServerMigrationTests(fixture).CreateDatabaseAsync();

    /// <summary>Creates an empty database with a user for the app login.</summary>
    private async Task<(string Owner, string App)> CreateDatabaseAsync()
    {
        var name = "mig_" + Guid.NewGuid().ToString("N")[..12];
        await using (var admin = new SqlConnection(_fixture.AdminConnectionString))
        {
            await admin.OpenAsync();
            await Execute(admin, $"CREATE DATABASE [{name}]");
        }

        var owner = new SqlConnectionStringBuilder(_fixture.AdminConnectionString) { InitialCatalog = name }
            .ConnectionString;
        await using (var connection = new SqlConnection(owner))
        {
            await connection.OpenAsync();
            await Execute(connection,
                "CREATE USER shop_app FOR LOGIN shop_app; GRANT SELECT, INSERT, UPDATE, DELETE TO shop_app;");
        }

        return (owner, new SqlConnectionStringBuilder(owner)
        {
            UserID = "shop_app",
            Password = SqlServerFixture.AppLoginPassword,
        }.ConnectionString);
    }

    internal static async Task<object?> Execute(SqlConnection connection, string sql, params (string, object)[] parameters)
    {
        await using var command = new SqlCommand(sql, connection);
        foreach (var (name, value) in parameters)
            command.Parameters.AddWithValue(name, value);
        return await command.ExecuteScalarAsync();
    }

    /// <summary>Generates the migration from source to target and runs it in one transaction.</summary>
    private static Task MigrateAsync(string owner, Action<ModelBuilder>? source, Action<ModelBuilder> target)
        => RunAsync(owner, Versions.Commands(source, target, owner));

    /// <summary>Runs generated commands like EF's migrator: in one transaction.</summary>
    internal static async Task RunAsync(string owner, IReadOnlyList<MigrationCommand> commands)
    {
        await using var context = MappingContext.Create(Versions.Empty, owner);
        await context.GetService<IMigrationCommandExecutor>().ExecuteNonQueryAsync(
            commands, context.GetService<IRelationalConnection>(),
            new MigrationExecutionState(), commitTransaction: true);
    }

    private static Task SetTenantAsync(SqlConnection connection, Guid tenant, string key = "TenantId")
        => Execute(connection, "EXEC sp_set_session_context @key = @k, @value = @t",
            ("@k", key), ("@t", tenant));

    /// <summary>Two tenants write a row each; each sees only its own and cannot write foreign rows.</summary>
    internal static async Task AssertIsolatedAsync(string app, string table, string column, string key = "TenantId")
    {
        Guid a = Guid.NewGuid(), b = Guid.NewGuid();
        await using var connection = new SqlConnection(app);
        await connection.OpenAsync();

        foreach (var tenant in new[] { a, b })
        {
            await SetTenantAsync(connection, tenant, key);
            await Execute(connection, $"INSERT INTO {table} ([{column}]) VALUES (@t)", ("@t", tenant));
        }

        await SetTenantAsync(connection, a, key);
        Assert.Equal(0, await Execute(connection,
            $"SELECT count(*) FROM {table} WHERE [{column}] <> @t", ("@t", a)));
        Assert.Equal(1, await Execute(connection,
            $"SELECT count(*) FROM {table} WHERE [{column}] = @t", ("@t", a)));

        var ex = await Assert.ThrowsAsync<SqlException>(() => Execute(connection,
            $"INSERT INTO {table} ([{column}]) VALUES (@t)", ("@t", b)));
        Assert.Equal(33504, ex.Number);                   // BLOCK PREDICATE
    }

    private static async Task<int> PluginPolicyCountAsync(string owner)
    {
        await using var connection = new SqlConnection(owner);
        await connection.OpenAsync();
        return (int)(await Execute(connection,
            "SELECT count(*) FROM sys.security_policies WHERE name LIKE N'tenant[_]%'"))!;
    }

    [Fact]
    public async Task Rename_move_back_and_drop_keep_the_table_isolated()
    {
        var (owner, app) = await CreateDatabaseAsync();

        await MigrateAsync(owner, null, Versions.V1);
        await AssertIsolatedAsync(app, "[dbo].[Invoice]", "TenantId");

        // Up: before the fix, sp_rename failed with "object participates in enforced dependencies"
        await MigrateAsync(owner, Versions.V1, Versions.ColumnRenamed);
        await AssertIsolatedAsync(app, "[dbo].[Invoice]", "Mandant");

        await MigrateAsync(owner, Versions.ColumnRenamed, Versions.TableRenamed);
        await AssertIsolatedAsync(app, "[dbo].[Bills]", "Mandant");

        await MigrateAsync(owner, Versions.TableRenamed, Versions.SchemaMoved);
        await AssertIsolatedAsync(app, "[sales].[Bills]", "Mandant");

        // Down, step by step
        await MigrateAsync(owner, Versions.SchemaMoved, Versions.TableRenamed);
        await AssertIsolatedAsync(app, "[dbo].[Bills]", "Mandant");

        await MigrateAsync(owner, Versions.TableRenamed, Versions.ColumnRenamed);
        await AssertIsolatedAsync(app, "[dbo].[Invoice]", "Mandant");

        await MigrateAsync(owner, Versions.ColumnRenamed, Versions.V1);
        await AssertIsolatedAsync(app, "[dbo].[Invoice]", "TenantId");
        Assert.Equal(1, await PluginPolicyCountAsync(owner));

        // Drop: the policy has to go first, and none may be left behind
        await MigrateAsync(owner, Versions.V1, Versions.Empty);
        Assert.Equal(0, await PluginPolicyCountAsync(owner));
    }

    [Fact]
    public async Task Same_table_name_in_two_schemas_is_isolated_in_both()
    {
        var (owner, app) = await CreateDatabaseAsync();

        await MigrateAsync(owner, null, m =>
        {
            m.Entity<Invoice>();
            m.Entity<ArchivedInvoice>().ToTable("Invoice", "archive");
        });

        await AssertIsolatedAsync(app, "[dbo].[Invoice]", "TenantId");
        await AssertIsolatedAsync(app, "[archive].[Invoice]", "TenantId");
    }

    [Fact]
    public async Task Policy_with_the_pre_1_1_name_is_found_and_replaced()
    {
        var (owner, app) = await CreateDatabaseAsync();
        await MigrateAsync(owner, null, Versions.V1);

        // An installation from 1.0: same policy, name without the schema
        await using (var connection = new SqlConnection(owner))
        {
            await connection.OpenAsync();
            await Execute(connection, "DROP SECURITY POLICY [acme].[tenant_dbo_Invoice]");
            await Execute(connection,
                "CREATE SECURITY POLICY [acme].[tenant_Invoice] "
                + "ADD FILTER PREDICATE [acme].[fn_tenant_predicate]([TenantId]) ON [dbo].[Invoice], "
                + "ADD BLOCK PREDICATE [acme].[fn_tenant_predicate]([TenantId]) ON [dbo].[Invoice] AFTER INSERT, "
                + "ADD BLOCK PREDICATE [acme].[fn_tenant_predicate]([TenantId]) ON [dbo].[Invoice] AFTER UPDATE "
                + "WITH (STATE = ON)");
        }

        await MigrateAsync(owner, Versions.V1, Versions.ColumnRenamed);

        await AssertIsolatedAsync(app, "[dbo].[Invoice]", "Mandant");
        await using var check = new SqlConnection(owner);
        await check.OpenAsync();
        Assert.Equal("tenant_dbo_Invoice", await Execute(check,
            "SELECT name FROM sys.security_policies WHERE name LIKE N'tenant[_]%'"));
    }

    [Fact]
    public async Task Policy_of_someone_else_on_a_table_without_tenant_isolation_survives()
    {
        var (owner, _) = await CreateDatabaseAsync();
        await MigrateAsync(owner, null, m => m.Entity<Note>());

        await using var connection = new SqlConnection(owner);
        await connection.OpenAsync();
        await Execute(connection,
            "EXEC(N'CREATE FUNCTION dbo.fn_owner(@Owner nvarchar(max)) RETURNS TABLE WITH SCHEMABINDING "
            + "AS RETURN SELECT 1 AS Allowed WHERE @Owner = USER_NAME()')");
        await Execute(connection,
            "CREATE SECURITY POLICY dbo.notes_by_owner ADD FILTER PREDICATE dbo.fn_owner([Owner]) ON dbo.Note");

        // Renaming a column of the table triggers the plugin's policy handling for it
        await MigrateAsync(owner, m => m.Entity<Note>(),
            m => m.Entity<Note>().Property(n => n.Text).HasColumnName("Body"));

        Assert.Equal(1, await Execute(connection,
            "SELECT count(*) FROM sys.security_policies WHERE name = N'notes_by_owner'"));
    }
}
