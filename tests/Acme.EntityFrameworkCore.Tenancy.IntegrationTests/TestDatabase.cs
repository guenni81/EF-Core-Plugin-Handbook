using Acme.EntityFrameworkCore.Tenancy.Interceptors;
using Acme.EntityFrameworkCore.Tenancy.PostgreSQL.Infrastructure;
using Acme.EntityFrameworkCore.Tenancy.PostgreSQL.Migrations.Operations;
using Acme.EntityFrameworkCore.Tenancy.PostgreSQL.Runtime;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using Microsoft.EntityFrameworkCore.Storage;
using Npgsql;
using Npgsql.EntityFrameworkCore.PostgreSQL.Infrastructure;

namespace Acme.EntityFrameworkCore.Tenancy.IntegrationTests;

/// <summary>
/// A database of its own per test, in the fixture's container: owner and app connection
/// strings, options with the plugin, schema creation and generated migrations.
/// </summary>
internal static class TestDatabase
{
    /// <summary>Creates an empty database; the app role exists server-wide.</summary>
    public static async Task<(string Owner, string App)> CreateAsync(PostgresFixture fixture)
    {
        var name = "db_" + Guid.NewGuid().ToString("N")[..12];
        await using (var admin = new NpgsqlConnection(fixture.OwnerConnectionString))
        {
            await admin.OpenAsync();
            await using var create = new NpgsqlCommand($"CREATE DATABASE {name}", admin);
            await create.ExecuteNonQueryAsync();
        }

        return (new NpgsqlConnectionStringBuilder(fixture.OwnerConnectionString) { Database = name }
                .ConnectionString,
            new NpgsqlConnectionStringBuilder(fixture.AppConnectionString) { Database = name }
                .ConnectionString);
    }

    /// <summary>Options with the plugin; with a tenant provider also the runtime interceptors.</summary>
    public static DbContextOptions<TContext> Options<TContext>(
        string connectionString,
        ITenantProvider? tenants = null,
        Action<NpgsqlDbContextOptionsBuilder>? npgsql = null,
        Action<TenancyOptionsBuilder>? tenancy = null)
        where TContext : DbContext
    {
        var builder = new DbContextOptionsBuilder<TContext>()
            .UseNpgsql(connectionString, npgsql)
            .UseAcmeTenancy(tenancy ?? (t => t.ApplyQueryFilter(false)))   // only RLS protects
            .EnableServiceProviderCaching(false);

        if (tenants is not null)
            builder.AddInterceptors(
                new TenantConnectionInterceptor(tenants),
                new TenantSaveChangesInterceptor(tenants));

        return builder.Options;
    }

    /// <summary>Creates the schema as owner and grants the app role access to it.</summary>
    public static async Task CreateSchemaAsync(DbContext owner)
    {
        await owner.Database.EnsureCreatedAsync();
        await RunAsync(owner, [new GrantTablePrivilegesOperation { Role = PostgresFixture.AppRole }]);
    }

    /// <summary>
    /// Diff from source to target, generated by EF and the plugin, run in one transaction;
    /// optionally with operations before and after the diff.
    /// </summary>
    public static async Task MigrateAsync(
        DbContext? source, DbContext target, IEnumerable<MigrationOperation>? before = null,
        IEnumerable<MigrationOperation>? after = null)
    {
        var operations = target.GetService<IMigrationsModelDiffer>().GetDifferences(
            source?.GetService<IDesignTimeModel>().Model.GetRelationalModel(),
            target.GetService<IDesignTimeModel>().Model.GetRelationalModel());
        await RunAsync(target, [.. before ?? [], .. operations, .. after ?? []]);
    }

    /// <summary>Generates and runs operations like EF's migrator: in one transaction.</summary>
    public static async Task RunAsync(DbContext context, IReadOnlyList<MigrationOperation> operations)
    {
        var commands = context.GetService<IMigrationsSqlGenerator>()
            .Generate(operations, context.GetService<IDesignTimeModel>().Model);
        await context.GetService<IMigrationCommandExecutor>().ExecuteNonQueryAsync(
            commands, context.GetService<IRelationalConnection>(),
            new MigrationExecutionState(), commitTransaction: true);
    }

    /// <summary>First column of the first row.</summary>
    public static async Task<object?> ScalarAsync(string connectionString, string sql)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        return await command.ExecuteScalarAsync();
    }
}
